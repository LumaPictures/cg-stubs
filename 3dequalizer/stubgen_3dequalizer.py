"""Generate Python stubs for 3DEqualizer4's `tde4` and `vl_sdv` modules.

`tde4` is a built-in C module that can't be imported and introspected
standalone, so its stubs are parsed from the vendor's "Python Doc (LLM)" -- a
JSON API doc published at 3dequalizer.com.  `vl_sdv` is pure python, so it is
generated by runtime inspection of the shipped module.

See the README for the download and setup; run with
`nox -s 'generate(3dequalizer)'`.
"""

